// Writes dist/sw.js after each build, so the app installs and works offline.
// - Precached on install: every page, script, stylesheet, font, the data files and icons
//   (the whole app is small, and it must work in a lab or on a plane).
// - Pages and data: network first (always the latest when online), saved copy offline.
// - Hashed assets (_astro/): cache first; their names change when they do.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

export default function pwa() {
  let base = '/';
  return {
    name: 'uu-pwa',
    hooks: {
      'astro:config:done': ({ config }) => { base = config.base.replace(/\/?$/, '/'); },
      'astro:build:done': ({ dir }) => {
        const out = fileURLToPath(dir), files = [], hash = createHash('sha256');
        const walk = (d) => { for (const n of readdirSync(d).sort()) { const p = path.join(d, n); if (statSync(p).isDirectory()) walk(p); else if (!/\.(png)$/.test(n) || /icon-192|apple-touch/.test(n)) files.push(p); } };
        walk(out);
        const urls = [];
        for (const f of files) {
          const rel = path.relative(out, f).split(path.sep).join('/');
          if (rel === 'sw.js' || rel === '.nojekyll') continue;
          hash.update(rel).update(readFileSync(f));
          urls.push(base + (rel.endsWith('index.html') ? rel.slice(0, -'index.html'.length) : rel));
        }
        const version = hash.digest('hex').slice(0, 12);
        writeFileSync(path.join(out, 'sw.js'), sw(version, base, urls));
        console.log(`pwa: sw.js ${version}, ${urls.length} files precached`);
      },
    },
  };
}

const sw = (version, base, urls) => `// Generated by integrations/pwa.mjs. Do not edit.
const V = ${JSON.stringify(version)}, SHELL = 'uu-shell-' + V, ASSETS = 'uu-assets', BASE = ${JSON.stringify(base)};
const PRE = ${JSON.stringify(urls)};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(SHELL).then((c) => c.addAll(PRE)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => { e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => (k.startsWith('uu-shell-') && k !== SHELL) || k.startsWith('ran-trainer-')).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', (e) => {
  const r = e.request, url = new URL(r.url);
  if (r.method !== 'GET' || url.origin !== location.origin || !url.pathname.startsWith(BASE)) return;
  if (url.pathname.includes('/_astro/')) { e.respondWith(caches.match(r).then((hit) => hit || fetch(r).then((res) => { const c = res.clone(); caches.open(ASSETS).then((x) => x.put(r, c)); return res; }))); return; }
  e.respondWith(fetch(r).then((res) => { if (res.ok) { const c = res.clone(); caches.open(SHELL).then((x) => x.put(r, c)); } return res; })
    .catch(() => caches.match(r, { ignoreSearch: true }).then((hit) => hit || caches.match(BASE))));
});
`;
